export function drawTinyText(raster: Raster, x: number, y: number, text: string, color = '#222222', scale = 1): void {
  let cursor = x;
  for (const char of text.toLowerCase().slice(0, 36)) {
    const glyph = GLYPHS[char];
    if (glyph) for (let row = 0; row < glyph.length; row += 1) for (let col = 0; col < glyph[row]!.length; col += 1) {
      if (glyph[row]![col] === '1') for (let dy = 0; dy < scale; dy += 1) for (let dx = 0; dx < scale; dx += 1) raster.pixel(cursor + col * scale + dx, y + row * scale + dy, color);
    }
    cursor += 4 * scale;
  }
}
